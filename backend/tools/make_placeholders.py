# фоновые цвета по юнитам (каждые 5 уроков)
UNIT_BG = [
    (225, 242, 249), (224, 240, 236), (247, 240, 224),
    (235, 228, 245), (224, 238, 248), (245, 230, 228),
]
AQUA, INK, MUTED = (16, 120, 165), (12, 58, 76), (120, 140, 152)


def font(size, bold=False):
    names = (["DejaVuSans-Bold.ttf"] if bold else ["DejaVuSans.ttf"])
    for n in names:
        try:
            return ImageFont.truetype(n, size)
        except OSError:
            continue
    return ImageFont.load_default()


def build():
    OUT.mkdir(parents=True, exist_ok=True)
    W, H = 800, 500
    for slug, num, topic, hint in SLOTS:
        bg = UNIT_BG[(num - 1) // 5]
        img = Image.new("RGB", (W, H), bg)
        d = ImageDraw.Draw(img)

        # рамка-пунктир
        for x in range(20, W - 20, 22):
            d.line([(x, 20), (x + 11, 20)], fill=MUTED, width=2)
            d.line([(x, H - 20), (x + 11, H - 20)], fill=MUTED, width=2)
        for y in range(20, H - 20, 22):
            d.line([(20, y), (20, y + 11)], fill=MUTED, width=2)
            d.line([(W - 20, y), (W - 20, y + 11)], fill=MUTED, width=2)

        # номер урока в кружке
        d.ellipse([40, 40, 120, 120], fill=AQUA)
        t = f"{num:02d}"
        f1 = font(44, bold=True)
        tb = d.textbbox((0, 0), t, font=f1)
        d.text((80 - (tb[2] - tb[0]) / 2, 80 - (tb[3] - tb[1]) / 2 - tb[1]),
               t, fill="white", font=f1)

        # тема
        d.text((150, 55), topic, fill=INK, font=font(38, bold=True))
        d.text((150, 105), "ЗАГЛУШКА — вставь свою картинку", fill=MUTED, font=font(20))

        # что показать
        d.text((60, 250), "На картинке:", fill=MUTED, font=font(22))
        d.text((60, 285), hint, fill=AQUA, font=font(30, bold=True))

        # имя файла
        d.text((60, H - 70), f"файл:  water/{slug}.jpg", fill=INK, font=font(20))

        img.save(OUT / f"{slug}.jpg", quality=82)
    print(f"Готово: {len(SLOTS)} заглушек в {OUT}")


if __name__ == "__main__":
    build()
